import { exec, execSync } from "child_process";
import { promisify } from "util";
import path from "path";
import fs from "fs/promises";
import fsSync from "fs";
import process from "process";
import * as yaml from "yaml";
import { Log } from "@utils/logger";
import { safe, safeSync } from "@utils/data-utils";

const execAsync = promisify(exec);

const CONFIG = {
  serviceName: "my-postgres",
  containerName: "my-postgres",
  image: "postgres:15",
  hostPort: 6000,
  containerPort: 5432,
  user: "postgres",
  password: "postgres",
  database: "mydb",
  volumeDir: "./data/postgres",
};

const cwd = process.cwd();
const ENV_FILE = path.join(cwd, ".env");
const COMPOSE_DIR = path.join(process.cwd(), "postgres_db");
const COMPOSE_FILE_EXT = path.join(COMPOSE_DIR, "docker-compose");
const COMPOSE_FILE = `${COMPOSE_FILE_EXT}.yaml`;

export class DbManager {
  static generateFilesSync() {
    DbManager.generateEnvFileSync();
    DbManager.generateComposeFileSync();
  }

  static async generateFilesAsync() {
    await DbManager.generateEnvFileAsync();
    await DbManager.generateComposeFileAsync();
  }

  static getEnvFile() {
    const envContent = `# Generated by db-manager.ts
DATABASE_URL=postgresql://${CONFIG.user}:${CONFIG.password}@localhost:${CONFIG.hostPort}/${CONFIG.database}?schema=public
DB_USER=${CONFIG.user}
DB_PASSWORD=${CONFIG.password}
DB_NAME=${CONFIG.database}
DB_PORT=${CONFIG.hostPort}
`;
    return envContent;
  }

  // ========== Генерация .env файла ==========
  static generateEnvFileSync() {
    const envContent = DbManager.getEnvFile();
    if (!fsSync.existsSync(ENV_FILE)) {
      fsSync.writeFileSync(ENV_FILE, envContent);
      console.log(`✅ Created ${ENV_FILE}`);
    } else {
      console.log(`ℹ️  ${ENV_FILE} already exists. Using existing configuration.`);
    }
  }

  static async generateEnvFileAsync() {
    const envContent = DbManager.getEnvFile();
    try {
      await fs.access(ENV_FILE);
      console.log(`ℹ️  ${ENV_FILE} already exists. Using existing configuration.`);
    } catch {
      await fs.writeFile(ENV_FILE, envContent);
      console.log(`✅ Created ${ENV_FILE}`);
    }
  }

  static makeComposeFile() {
    const composeConfig = {
      version: "3.8",
      services: {
        [CONFIG.serviceName]: {
          image: CONFIG.image,
          container_name: CONFIG.containerName,
          restart: "unless-stopped",
          ports: [`${CONFIG.hostPort}:${CONFIG.containerPort}`],
          environment: {
            POSTGRES_USER: CONFIG.user,
            POSTGRES_PASSWORD: CONFIG.password,
            POSTGRES_DB: CONFIG.database,
          },
          volumes: [`${CONFIG.volumeDir}:/var/lib/postgresql/data`],
        },
      },
    };
    return composeConfig;
  }

  // ========== Вспомогательная генерация compose-файла ==========
  static async generateComposeFileAsync() {
    await fs.mkdir(COMPOSE_DIR, { recursive: true });
    const composeConfig = DbManager.makeComposeFile();
    // Записываем JSON-файл с красивым форматированием
    await fs.writeFile(`${COMPOSE_FILE_EXT}.yaml`, yaml.stringify(composeConfig));
    // await fs.writeFile(`${COMPOSE_FILE_EXT}.json`, JSON.stringify(composeConfig, null, 2));

    console.log(`Generated ${COMPOSE_FILE}`);
  }

  static generateComposeFileSync() {
    fsSync.mkdirSync(COMPOSE_DIR, { recursive: true });
    const composeConfig = DbManager.makeComposeFile();
    fsSync.writeFileSync(`${COMPOSE_FILE_EXT}.yaml`, yaml.stringify(composeConfig));
    // fsSync.writeFileSync(`${COMPOSE_FILE_EXT}.json`, JSON.stringify(composeConfig, null, 2));
    console.log(`Generated ${COMPOSE_FILE}`);
  }

  // ========== Примитивы: запуск контейнера (без ожидания) ==========
  static startContainerSync() {
    console.log("Starting PostgreSQL container (sync, no wait)...");
    try {
      execSync(`docker compose -f ${COMPOSE_FILE} up -d`, { stdio: "inherit" });
      console.log("Container started.");
    } catch (error) {
      console.error("Failed to start container:", error);
      throw error;
    }
  }

  static async startContainerAsync() {
    console.log("Starting PostgreSQL container (async, no wait)...");
    try {
      await execAsync(`docker-compose -f ${COMPOSE_FILE} up -d`);
      console.log("Container started.");
    } catch (error) {
      console.error("Failed to start container:", error);
      throw error;
    }
  }
  static _IsReady() {
    const stdout = execSync(`docker compose -f ${COMPOSE_FILE} exec -T ${CONFIG.serviceName} pg_isready -U ${CONFIG.user}`, { encoding: "utf-8" });
    if (stdout.includes("accepting connections")) {
      console.log("Database is ready!");
      return true;
    }
    return false;
  }
  static async _IsReadyAsync() {
    const { stdout } = await execAsync(`docker compose -f ${COMPOSE_FILE} exec -T ${CONFIG.serviceName} pg_isready -U ${CONFIG.user}`);
    if (stdout.includes("accepting connections")) {
      console.log("Database is ready!");
      return true;
    }
    return false;
  }
  static IsReady() {
    return safeSync(() => DbManager._IsReady(), false);
  }
  static async IsReadyAsync() {
    return await safe(() => DbManager._IsReadyAsync(), false);
  }
  // ========== Примитивы: ожидание готовности ==========
  static waitForDatabaseReadySync(maxRetries = 30, delayMs = 2000) {
    console.log("Waiting for database to be ready (sync)...");
    for (let i = 0; i < maxRetries; i++) {
      if (DbManager.IsReady()) return true;
      console.log(`Attempt ${i + 1}/${maxRetries}: Database not ready yet.`);
      execSync(`sleep ${delayMs / 1000}`);
    }
    return false;
    throw new Error("Database did not become ready in time.");
  }

  static async waitForDatabaseReadyAsync(maxRetries = 30, delayMs = 2000) {
    console.log("Waiting for database to be ready (async)...");
    for (let i = 0; i < maxRetries; i++) {
      if (await DbManager.IsReadyAsync()) return true;
      console.log(`Attempt ${i + 1}/${maxRetries}: Database not ready yet.`);
      await new Promise((resolve) => setTimeout(resolve, delayMs));
    }
    return false;
    throw new Error("Database did not become ready in time.");
  }

  // ========== Примитивы: запуск + ожидание (комбинированные) ==========
  @Log
  static startAndWaitSync() {
    if (DbManager.IsReady()) return true;
    DbManager.generateFilesSync();
    DbManager.startContainerSync();
    return DbManager.waitForDatabaseReadySync();
  }
  @Log
  static async startAndWaitAsync() {
    if (await DbManager.IsReadyAsync()) return true;
    await DbManager.generateFilesAsync();
    await DbManager.startContainerAsync();
    return await DbManager.waitForDatabaseReadyAsync();
  }

  // ========== Примитивы: остановка ==========
  static stopContainerSync() {
    console.log("Stopping PostgreSQL container (sync)...");
    try {
      execSync(`docker-compose -f ${COMPOSE_FILE} down`, { stdio: "inherit" });
      console.log("Container stopped.");
    } catch (error) {
      console.error("Failed to stop container:", error);
      throw error;
    }
  }

  static async stopContainerAsync() {
    console.log("Stopping PostgreSQL container (async)...");
    try {
      await execAsync(`docker-compose -f ${COMPOSE_FILE} down`);
      console.log("Container stopped.");
    } catch (error) {
      console.error("Failed to stop container:", error);
      throw error;
    }
  }

  // ========== Регистрация обработчиков завершения ==========
  static registerShutdownHandlers() {
    process.on("exit", (code) => {
      try {
        DbManager.stopContainerSync();
      } catch (e) {
        console.error("Error stopping container on exit:", e);
      }
    });

    const handleSignal = (signal: string) => {
      console.log(`Received ${signal}, stopping container...`);
      try {
        DbManager.stopContainerSync();
      } catch (e) {
        console.error(`Error stopping container on ${signal}:`, e);
      }
      process.exit(0);
    };

    process.on("SIGINT", handleSignal);
    process.on("SIGTERM", handleSignal);
  }

  // ========== Функции высокого уровня ==========

  /**
   * Синхронно запускает контейнер, выполняет колбэк, затем синхронно останавливает.
   * Гарантирует остановку даже при ошибке в колбэке.
   */
  static runWithCallbackSync<T>(callback: () => T): T {
    DbManager.startAndWaitSync();
    DbManager.registerShutdownHandlers();
    try {
      return callback();
    } finally {
      DbManager.stopContainerSync();
    }
  }

  /**
   * Асинхронно запускает контейнер, ожидает переданный промис, затем асинхронно останавливает.
   * Гарантирует остановку даже при ошибке.
   */
  static async runWithPromiseAsync<T>(promise: Promise<T>): Promise<T> {
    await DbManager.startAndWaitAsync();
    DbManager.registerShutdownHandlers();
    try {
      return await promise;
    } finally {
      await DbManager.stopContainerAsync().catch((e) => console.error("Error stopping container:", e));
    }
  }

  /**
   * Синхронно запускает контейнер, регистрирует обработчики для автоматической остановки при выходе,
   * и сразу возвращает управление. Подходит для случаев, когда приложение продолжает работу,
   * а контейнер должен жить до завершения процесса.
   */
  static runWithAppLifecycleSync(): void {
    DbManager.startAndWaitSync();
    DbManager.registerShutdownHandlers();
    console.log("Database container is running (sync). It will be stopped automatically on process exit.");
  }

  /**
   * Асинхронно запускает контейнер, регистрирует обработчики для автоматической остановки при выходе,
   * и сразу возвращает управление (после готовности БД). Не содержит бесконечного ожидания.
   */
  static async runWithAppLifecycleAsync(): Promise<void> {
    await DbManager.startAndWaitAsync();
    DbManager.registerShutdownHandlers();
    console.log("Database container is running (async). It will be stopped automatically on process exit.");
  }
  static commander(command: string) {
    if (command === "up") {
      DbManager.startAndWaitSync();
    } else if (command === "down") {
      DbManager.stopContainerSync();
    }
  }
}
// ========== Обработка команд из командной строки ==========
if (require.main === module) {
  const command = process.argv[2];
  DbManager.commander(command);
  if (false) {
    // По умолчанию используем runWithAppLifecycleAsync (не блокирует)
    DbManager.runWithAppLifecycleAsync().catch(console.error);
  }
}
